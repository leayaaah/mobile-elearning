-- ---------- Danh mục & dữ liệu công khai ----------
create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  icon text,            -- tên icon Feather (vd: "code")
  color text            -- mã màu hex cho ô danh mục
);

create table public.teachers (
  id bigint generated by default as identity primary key,
  full_name text not null,
  headline text,
  avatar_url text,
  cover_url text,
  location text,
  bio text,
  followers_count int not null default 0
);

create table public.courses (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  thumbnail_url text,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  category_id bigint not null references public.categories(id),
  price numeric(10,2) not null,              -- giá bán (đã giảm)
  original_price numeric(10,2),              -- giá gốc
  discount_percent int not null default 0,
  badge text check (badge in ('best-seller','discount')),
  rating numeric(2,1) not null default 0,
  rating_count int not null default 0,
  lessons_count int not null default 0,
  duration_minutes int not null default 0,
  is_popular boolean not null default false,
  is_recommended boolean not null default false,
  is_inspiring boolean not null default false,
  created_at timestamptz not null default now()
);
create index courses_category_idx on public.courses(category_id);
create index courses_teacher_idx on public.courses(teacher_id);

create table public.sections (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  title text not null,
  position int not null
);

create table public.lessons (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.sections(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  title text not null,
  duration_seconds int not null default 0,
  position int not null,
  video_url text,
  is_preview boolean not null default false
);
create index lessons_course_idx on public.lessons(course_id);

create table public.reviews (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  reviewer_name text not null,
  reviewer_avatar text,
  rating smallint not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);
create index reviews_course_idx on public.reviews(course_id);

create table public.course_resources (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  name text not null,
  size_label text,
  url text
);

create table public.qa_posts (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  author_name text not null,
  author_avatar text,
  content text not null,
  likes_count int not null default 0,
  comments_count int not null default 0,
  created_at timestamptz not null default now()
);
create index qa_course_idx on public.qa_posts(course_id);

-- ---------- Dữ liệu theo người dùng ----------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  headline text,
  avatar_url text,
  cover_url text,
  created_at timestamptz not null default now()
);

create table public.bookmarks (
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, course_id)
);

create table public.cart_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (user_id, course_id)
);

create table public.enrollments (
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  primary key (user_id, course_id)
);

create table public.lesson_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  completed_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

-- Đơn hàng (dùng cho phần thanh toán giả lập)
create table public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  total numeric(10,2) not null,
  status text not null default 'paid',
  created_at timestamptz not null default now()
);
create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  course_id bigint not null references public.courses(id),
  price numeric(10,2) not null
);

-- ---------- View: khóa học của tôi + tiến độ ----------
create view public.my_courses with (security_invoker = true) as
select
  e.user_id,
  e.course_id,
  c.title,
  c.thumbnail_url,
  c.duration_minutes,
  c.lessons_count,
  count(lp.lesson_id)::int as completed_lessons,
  case when c.lessons_count > 0
       then round(100.0 * count(lp.lesson_id) / c.lessons_count)::int
       else 0 end as progress
from public.enrollments e
join public.courses c on c.id = e.course_id
left join public.lesson_progress lp
  on lp.user_id = e.user_id and lp.course_id = e.course_id
group by e.user_id, e.course_id, c.id;

-- ---------- Tự tạo profile khi đăng ký ----------
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', ''));
  return new;
end $$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- ---------- Thanh toán giả lập (bước mở rộng): 1 lệnh gọi, nguyên tử ----------
create or replace function public.checkout_cart()
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_order bigint;
  v_total numeric;
begin
  if v_uid is null then raise exception 'Chưa đăng nhập'; end if;
  if not exists (select 1 from cart_items where user_id = v_uid) then
    raise exception 'Giỏ hàng trống';
  end if;

  select coalesce(sum(c.price), 0) into v_total
  from cart_items ci join courses c on c.id = ci.course_id
  where ci.user_id = v_uid;

  insert into orders (user_id, total) values (v_uid, v_total) returning id into v_order;

  insert into order_items (order_id, course_id, price)
  select v_order, c.id, c.price
  from cart_items ci join courses c on c.id = ci.course_id
  where ci.user_id = v_uid;

  insert into enrollments (user_id, course_id)
  select v_uid, course_id from cart_items where user_id = v_uid
  on conflict do nothing;

  delete from cart_items where user_id = v_uid;
  return v_order;
end $$;
grant execute on function public.checkout_cart() to authenticated;


-- ---------- Thanh toán giả lập (bước mở rộng): 1 lệnh gọi, nguyên tử ----------
create or replace function public.checkout_cart()
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_order bigint;
  v_total numeric;
begin
  if v_uid is null then raise exception 'Chưa đăng nhập'; end if;
  if not exists (select 1 from cart_items where user_id = v_uid) then
    raise exception 'Giỏ hàng trống';
  end if;

  select coalesce(sum(c.price), 0) into v_total
  from cart_items ci join courses c on c.id = ci.course_id
  where ci.user_id = v_uid;

  insert into orders (user_id, total) values (v_uid, v_total) returning id into v_order;

  insert into order_items (order_id, course_id, price)
  select v_order, c.id, c.price
  from cart_items ci join courses c on c.id = ci.course_id
  where ci.user_id = v_uid;

  insert into enrollments (user_id, course_id)
  select v_uid, course_id from cart_items where user_id = v_uid
  on conflict do nothing;

  delete from cart_items where user_id = v_uid;
  return v_order;
end $$;
grant execute on function public.checkout_cart() to authenticated;

